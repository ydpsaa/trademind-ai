from pathlib import Path
import json
from playwright.sync_api import sync_playwright
base=Path(__file__).resolve().parents[1]
html=(base/'preview/index.html').read_text().replace('<script src="quant-lab.bundle.js"></script><script src="app.js"></script>','')
checks=[]
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1000},accept_downloads=True)
    errors=[]
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.set_content(html)
    page.add_script_tag(content=(base/'preview/quant-lab.bundle.js').read_text())
    page.add_script_tag(content=(base/'preview/app.js').read_text())
    page.locator('#run').click()
    assert page.locator('#results').is_visible() and page.locator('#chart polyline').count()==1
    checks.append('initial backtest and computed equity curve')
    page.screenshot(path=str(base/'docs/quant-lab-desktop.png'),full_page=True)
    for name in ['Momentum','Mean Reversion','Breakout','Pairs Trading','Trend Following']:
        page.get_by_role('button',name=name,exact=True).click()
        page.locator('#run').click()
        assert page.locator('#results').is_visible(), page.locator('#run-error').inner_text()
        assert name in page.locator('#result-label').inner_text()
    checks.append('all five bar-based strategy models run')
    page.get_by_role('button',name='Market Making',exact=True).click()
    page.locator('#quote-run').click()
    assert page.locator('#results').is_visible() and page.locator('#chart-section').is_hidden()
    assert 'Bid' in page.locator('#metrics').inner_text()
    checks.append('market making quote sandbox separate from backtest')
    page.get_by_role('button',name='Trend Following',exact=True).click()
    page.locator('#run').click()
    page.locator('#slow').fill('500')
    assert page.locator('#results').is_hidden()
    page.locator('#run').click()
    assert 'insufficient' in page.locator('#run-error').inner_text()
    checks.append('parameter edits invalidate stale results; invalid warmup fails closed')
    with page.expect_download() as download:
        page.locator('#sample').click()
    csvpath=download.value.path()
    page.locator('#csv').set_input_files(str(csvpath))
    page.wait_for_function("document.getElementById('source').textContent.includes('Unverified user CSV')")
    page.locator('#slow').fill('50')
    page.locator('#run').click()
    assert page.locator('#results').is_visible()
    assert 'user-supplied' in page.locator('#result-label').inner_text()
    checks.append('CSV import and explicit unverified provenance')
    with page.expect_download() as d:
        page.locator('#export').click()
    report=json.loads(d.value.path().read_text())
    assert report['mode']=='sandbox' and report['sourceKind']=='user-supplied'
    checks.append('JSON export contains actual engine output and provenance')
    page.locator('#csv').set_input_files({'name':'bad.csv','mimeType':'text/csv','buffer':b'bad,data\n1,2'})
    page.wait_for_function("document.getElementById('data-error').textContent.includes('expected header')")
    checks.append('invalid CSV fails closed without replacing prior dataset')
    page.locator('#fixture').click()
    page.locator('#prop-run').click()
    assert page.locator('#prop-results').is_visible() and '84.40%' in page.locator('#prob-metrics').inner_text()
    checks.append('prop model renders exact reference and seeded simulation')
    page.locator('#sample-r').fill('2,2,2')
    assert page.locator('#prop-results').is_hidden()
    page.locator('#prop-run').click()
    assert '100.00%' in page.locator('#prob-metrics').inner_text() and 'N/A' in page.locator('#prob-metrics').inner_text()
    checks.append('empirical net-R input disables binary exact shortcut')
    page.set_viewport_size({'width':390,'height':844})
    page.get_by_role('button',name='Trend Following',exact=True).click()
    page.locator('#run').click()
    assert page.locator('#results').is_visible()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.screenshot(path=str(base/'docs/quant-lab-mobile.png'),full_page=True)
    checks.append('mobile viewport has no horizontal page overflow')
    assert not errors, errors
    checks.append('no browser runtime exceptions')
    browser.close()
for c in checks: print('PASS',c)
print(f'{len(checks)}/{len(checks)} browser checks passed')
